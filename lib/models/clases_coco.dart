/// Nombre en español de una clase de YOLO, con su artículo para hablar natural
/// ("la botella", "un celular").
class NombreClase {
  const NombreClase(this.nombre, this.articulo);

  final String nombre;

  /// 'el', 'la', 'los' o 'las'
  final String articulo;

  bool get esPlural => articulo == 'los' || articulo == 'las';

  String get indefinido {
    switch (articulo) {
      case 'la':
        return 'una';
      case 'el':
        return 'un';
      case 'las':
        return 'unas';
      default:
        return 'unos';
    }
  }

  String get conArticulo => '$articulo $nombre';
  String get conIndefinido => '$indefinido $nombre';
}

